            <h2 class="heading4">What a degree map Is not:</h2>
            
            <h3 class="heading6">Degree Audit</h3>
            
            <p>The degree maps do not replace the Degree Works audit. Degree Works is a web-based
               tool used to monitor a student's academic progress toward degree completion. It combines
               WSU's degree requirements with the courses a student is currently taking, has taken
               in the past, and plans to take. It produces a snapshot called a "degree audit" of
               the progress a student is making in fulfilling their degree requirements. Instructions
               on reading your degree audit are available at the <a href="/services/registrar/degreeaudit/FAQ.php">Degree Works FAQ</a>.</p>
            
            <h3 class="heading6">Undergraduate Catalog</h3>
            
            <p>Detailed information on degree requirements and course descriptions are available
               in the <a href="http://catalog.wichita.edu/undergraduate/">Wichita State University Undergraduate Catalog</a>. Also available in the Undergraduate Catalog is more detailed information on the
               <a href="http://catalog.wichita.edu/undergraduate/academic-information/general-education-program/">WSU General Education Program</a>.</p>
            
            <h3 class="heading6">Academic Advising</h3>
            
            <p>Degree maps do not replace the personalized service available to you through an academic
               advising appointment. Advising is much more than just building a schedule; it's an
               ongoing partnership between the student, advisors and advising staff to promote your
               success and help you graduate in a timely manner. Academic advisors form partnerships
               with students in the following ways:</p>
            
            <ul>
               
               <li>Assist students to set short- and long-term goals.</li>
               
               <li>Provide career information regarding the degree fields of interest.</li>
               
               <li>Inform students about university policies and procedures important to a student's
                  progress.</li>
               
               <li>Draw upon a comprehensive knowledge of campus resources and assist students in referral
                  and access to such services.</li>
               </ul>
            
            <p>To schedule an appointment with your <a href="/academics/advising/index.php">academic advisor</a>.</p>
